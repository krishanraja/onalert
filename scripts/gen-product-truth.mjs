#!/usr/bin/env node
/**
 * Single-source generator for OnAlert pricing + product truth.
 *
 * Reads the canonical data:
 *   src/data/pricing.json          (prices, limits, features)
 *   src/data/product-truth.base.json (curated ICP / brand / voice / capability status)
 *
 * Writes three derived artifacts so every consumer reads ONE source:
 *   supabase/functions/_shared/pricing.ts   -> checkout + webhook cents (committed; deterministic, no timestamp)
 *   public/.well-known/product-truth.json   -> the fleet's machine-readable truth (gitignored; regenerated each build)
 *   public/llms.txt                          -> agent-facing pitch brief (gitignored; regenerated each build)
 *
 * Run via: npm run gen:truth  (also runs automatically on prebuild + predev).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));

const pricing = read('src/data/pricing.json');
const base = read('src/data/product-truth.base.json');

const gitSha = (() => {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString().trim();
  } catch {
    return 'unknown';
  }
})();
const generatedAt = new Date().toISOString();
const SCHEMA_VERSION = 1;

const planIds = Object.keys(pricing.plans);
const paidIds = planIds.filter((id) => pricing.plans[id].priceCents > 0);
const aliases = pricing.legacyAliases || {};

// ----- PLAN_PRICES_CENTS (paid + legacy aliases) -----
const planPricesCents = {};
for (const id of paidIds) planPricesCents[id] = pricing.plans[id].priceCents;
for (const [alias, target] of Object.entries(aliases)) {
  planPricesCents[alias] = pricing.plans[target].priceCents;
}

// ----- STRIPE_PLANS (paid only) -----
const stripePlans = {};
for (const id of paidIds) {
  const p = pricing.plans[id];
  stripePlans[id] = { priceCents: p.priceCents, name: p.stripeName, description: p.stripeDescription };
}

const validPlanKeys = [...paidIds, ...Object.keys(aliases)];

// =========================================================
// 1) supabase/functions/_shared/pricing.ts  (Deno, committed)
// =========================================================
const paidUnion = paidIds.map((id) => `'${id}'`).join(' | ');
const ts = `// AUTO-GENERATED by scripts/gen-product-truth.mjs from src/data/pricing.json.
// DO NOT EDIT. Change prices in src/data/pricing.json and run \`npm run gen:truth\`.
// Single source of truth for checkout + webhook so create-checkout (what we charge)
// and stripe-webhook (what we validate) can never drift into amount-mismatch failures.

export type PaidPlan = ${paidUnion};
export type PlanId = 'free' | PaidPlan;

export const CURRENCY = '${pricing.currency}';
export const BILLING = '${pricing.billing}';
export const PAID_PLAN_IDS: PaidPlan[] = [${paidIds.map((id) => `'${id}'`).join(', ')}];

// Cents per plan, including legacy aliases accepted from historical sessions.
export const PLAN_PRICES_CENTS: Record<string, number> = ${JSON.stringify(planPricesCents, null, 2)};

// Stripe product metadata for one-time checkout sessions (paid plans only).
export const STRIPE_PLANS: Record<PaidPlan, { priceCents: number; name: string; description: string }> = ${JSON.stringify(stripePlans, null, 2)};

const LEGACY_ALIASES: Record<string, PaidPlan> = ${JSON.stringify(aliases, null, 2)};

/** Resolve a (possibly legacy) plan key to its canonical paid plan id. */
export function normalizePlan(plan: string): PaidPlan {
  return (LEGACY_ALIASES[plan] ?? plan) as PaidPlan;
}

/** True if \`plan\` is a chargeable plan key we accept (paid id or legacy alias). */
export function isValidPaidPlan(plan: string): plan is PaidPlan {
  return ${JSON.stringify(validPlanKeys)}.includes(plan);
}
`;
writeOut('supabase/functions/_shared/pricing.ts', ts);

// =========================================================
// 2) public/.well-known/product-truth.json  (fleet truth)
// =========================================================
const pricingForTruth = {
  currency: pricing.currency,
  billing: pricing.billing,
  legacyAliases: aliases,
  note: 'maxLocations null means unlimited. All plans are one-time payments.',
  plans: Object.fromEntries(
    planIds.map((id) => {
      const p = pricing.plans[id];
      return [id, {
        name: p.name,
        priceUsd: p.priceCents / 100,
        priceCents: p.priceCents,
        monitors: p.monitors,
        maxLocations: p.maxLocations,
        checkIntervalMinutes: p.checkInterval,
        cooldownHours: p.cooldown,
        channels: p.channels,
        features: p.features,
      }];
    })
  ),
};

const productTruth = {
  schemaVersion: SCHEMA_VERSION,
  generatedAt,
  gitSha,
  source: 'https://onalert.app/.well-known/product-truth.json',
  product: base.product,
  icp: base.icp,
  personas: base.personas,
  offerDecisionRules: base.offerDecisionRules,
  currentOffer: base.currentOffer,
  capabilityStatus: base.capabilityStatus,
  capabilityStatusNote: base.capabilityStatusNote,
  anchorStats: base.anchorStats,
  northStarMetric: base.northStarMetric,
  brand: base.brand,
  voice: base.voice,
  pricing: pricingForTruth,
  links: base.links,
};
writeOut('public/.well-known/product-truth.json', JSON.stringify(productTruth, null, 2) + '\n');

// =========================================================
// 3) public/llms.txt  (agent-facing pitch brief)
// =========================================================
const priceLine = (id) => {
  const p = pricing.plans[id];
  const loc = p.maxLocations === null ? 'unlimited locations' : `${p.maxLocations} locations`;
  const price = p.priceCents === 0 ? 'Free' : `$${p.priceCents / 100} one-time`;
  return `- ${p.name} (${price}): ${p.monitors} monitor${p.monitors > 1 ? 's' : ''}, ${loc}, checked every ${p.checkInterval} min, ${p.channels.join(' + ')}.`;
};
const personaLine = (x) => `- ${x.label} -> ${x.recommendedPlan} (signals: ${x.intentSignals.join('; ')}).`;
const liveCaps = Object.entries(base.capabilityStatus).filter(([, v]) => v === 'live').map(([k]) => k);
const notLiveCaps = Object.entries(base.capabilityStatus).filter(([, v]) => v !== 'live').map(([k, v]) => `${k}=${v}`);

const llms = `# OnAlert (${base.product.url})

> ${base.product.tagline}
${base.product.oneSentencePitch}

## What it is
${base.product.category}. Programs: ${base.product.programs.join(', ')}. ${base.product.programsNote}

## Who it is for
${base.icp.definition}

The painful problem: ${base.icp.painfulProblem}

The magic moment: ${base.icp.magicMoment}

## Pricing (all one-time, no subscription)
${planIds.map(priceLine).join('\n')}

## Who to recommend what
${base.personas.map(personaLine).join('\n')}

## Anchor facts (safe to cite)
- Typical wait: ${base.anchorStats.typicalWaitMonths} months.
- A cancellation slot is bookable for only ${base.anchorStats.slotBookableWindowMinutes} minutes.
- Express checks ${base.anchorStats.expressSpeedVsFree} faster than Free.
- ${base.anchorStats.enrollmentCenters} enrollment centers, ${base.anchorStats.programs} programs.
- TAM: ${base.anchorStats.tamConditionallyApproved} conditionally-approved applicants.

## Voice rules (follow when writing about OnAlert)
${base.voice.rules.map((r) => `- ${r}`).join('\n')}
- Never use these words: ${base.voice.bannedWords.join(', ')}.
- No em dashes.

## Capabilities that are LIVE
${liveCaps.map((c) => `- ${c}`).join('\n')}

## Do NOT claim these as live yet
${notLiveCaps.map((c) => `- ${c}`).join('\n')}

## Current offer
${base.currentOffer.active ? 'See product-truth.json.' : 'None active. Do not promise a money-back guarantee or referral discount.'}

## Machine-readable truth
${base.links.productTruth}

Generated ${generatedAt} (build ${gitSha}).
`;
writeOut('public/llms.txt', llms);

// =========================================================
// 4) public/sitemap.xml  (derived from TOP_LOCATIONS — single source)
// =========================================================
// The old sitemap was hand-maintained against stale location IDs (48 soft-404s, 43
// missing pages). Generate it from src/lib/locations.ts so it always matches the
// routes vite-react-ssg actually prerenders. Only public, indexable pages are listed
// (no /auth, /app, /404). Deterministic (no lastmod) so rebuilds produce no diff.
const SITE = ((base.product && base.product.url) || 'https://onalert.app').replace(/\/$/, '');
const locationsTs = readFileSync(resolve(root, 'src/lib/locations.ts'), 'utf8');
const locationIds = [...locationsTs.matchAll(/\{\s*id:\s*(\d+)/g)].map((m) => Number(m[1]));
if (locationIds.length === 0) {
  throw new Error('gen-product-truth: failed to parse any location IDs from src/lib/locations.ts');
}
const staticPages = [
  { path: '/', changefreq: 'weekly', priority: '1.0' },
  { path: '/wait-times', changefreq: 'daily', priority: '0.9' },
  { path: '/locations', changefreq: 'weekly', priority: '0.9' },
  { path: '/guide', changefreq: 'monthly', priority: '0.8' },
  { path: '/privacy', changefreq: 'yearly', priority: '0.3' },
  { path: '/terms', changefreq: 'yearly', priority: '0.3' },
];
const urlEntry = (path, changefreq, priority) =>
  `  <url>\n    <loc>${SITE}${path}</loc>\n    <changefreq>${changefreq}</changefreq>\n    <priority>${priority}</priority>\n  </url>`;
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${staticPages.map((p) => urlEntry(p.path, p.changefreq, p.priority)).join('\n')}
${locationIds.map((id) => urlEntry(`/locations/${id}`, 'weekly', '0.7')).join('\n')}
</urlset>
`;
writeOut('public/sitemap.xml', sitemap);

console.log(`gen-product-truth: wrote _shared/pricing.ts, product-truth.json, llms.txt, sitemap.xml (${locationIds.length} locations, build ${gitSha})`);

function writeOut(rel, contents) {
  const abs = resolve(root, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, contents);
}
